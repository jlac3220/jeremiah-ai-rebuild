// Function to expand search terms
export function expandSearchTerms(keywords) {
  const expanded = new Set(keywords);

  for (const keyword of keywords) {
    const lowerKeyword = keyword.toLowerCase();

    // Check direct matches
    if (theologicalSynonyms[lowerKeyword]) {
      theologicalSynonyms[lowerKeyword].forEach((syn) => expanded.add(syn));
    }

    // Check if keyword is contained in any synonym lists (reverse lookup)
    for (const [term, synonyms] of Object.entries(theologicalSynonyms)) {
      if (synonyms.includes(lowerKeyword)) {
        expanded.add(term);
        synonyms.forEach((syn) => expanded.add(syn));
      }
    }
  }

  return Array.from(expanded);
}
