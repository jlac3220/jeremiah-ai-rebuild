import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import './test-visual-framework.mjs';
const read = path => readFileSync(new URL(path,import.meta.url),'utf8');
const gallery = read('../src/features/classroom/JourneyDestinations.jsx');
const catalog = read('../src/data/curriculum/visualCatalog.js');
const lesson = read('../src/features/classroom/OG1LessonPlayer.jsx');
const shema = read('../src/features/classroom/ShemaExperience.jsx');
const classroom = read('../src/features/classroom/TeacherLedLesson.jsx');
const curriculum = read('../src/features/classroom/CurriculumLesson.jsx');
const outlet = read('../src/features/classroom/ContextualLessonImage.jsx');

assert.ok(catalog.includes('export const VISUAL_ASSETS'),'Shared asset registry must serve all standards');
assert.ok(gallery.includes('chooseLessonVisual('),'Journey images must use relevance selection');
assert.ok(shema.includes('chooseLessonVisual('),'Shema opening must use relevance selection');
assert.ok(outlet.includes('inferVisualPlacement('),'Generic classrooms must infer only source-supported placements');
assert.ok(classroom.includes('<ContextualLessonImage'),'Teacher-led classroom must use the shared outlet');
assert.ok(curriculum.includes('<ContextualLessonImage'),'Standards curriculum must use the shared outlet');
assert.ok(lesson.includes('APPLICATION_MOMENTS'),'Applications must describe the intent of each visual');
assert.ok(lesson.includes("intent:'general'"),'Generic worship may use generic relevant photography');
assert.ok(lesson.includes("intent:'artifact'"),'Manuscript lessons should request actual artifacts');
assert.ok(lesson.includes("intent:'historical'"),'Historical lessons must specify subject and reference');
assert.doesNotMatch(gallery,/BIBLICAL_ART\[tone\]\|\|BIBLICAL_ART\.moses/,'No generic Moses fallback');
assert.doesNotMatch(lesson,/scene\.type==='apostles'\|\|failed|index===2\?'apostles':'shema'/,'Do not substitute unrelated scenes when images fail');
assert.doesNotMatch(lesson,/Volunteers filling food|Volunteer packing|chooseEverydayPhoto|EverydayScenePhoto/);
assert.ok(lesson.includes('The one LORD is not one option'),'Keep the approved lesson text unchanged');
console.log('PASS: cross-standard image selection is used by OG, the teacher-led classroom, and curriculum lessons; unsupported images do not fall back to unrelated scenes.');
