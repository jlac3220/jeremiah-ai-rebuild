import assert from 'node:assert/strict';
import { getLearningDashboard } from '../src/core/classroom/learningDashboard.js';
import { classroomContentRegistry } from '../src/core/classroom/content/classroomContentRegistry.js';
import { createLearningState } from '../src/core/classroom/learningEngine.js';
const saved = new Map();
globalThis.window = { localStorage: { getItem: (key) => saved.get(key) || null } };
const content = Object.values(classroomContentRegistry)[0];
let data = getLearningDashboard();
assert.equal(data.mastered, 0);
assert.equal(data.inProgress, 0);
assert.equal(data.active.preset, 'direct');
assert.equal(data.active.percent, 0);
const direct = createLearningState(content, 'direct');
direct.milestones.started = true;
direct.experience.sceneIndex = 2;
direct.lastUpdatedAt = 100;
saved.set(`jeremiah-learning-state:${content.standardId}:direct`, JSON.stringify(direct));
data = getLearningDashboard();
assert.equal(data.inProgress, 1);
assert.equal(data.active.preset, 'direct');
assert.equal(data.active.state.experience.sceneIndex, 2);
const review = createLearningState(content, 'review');
review.milestones.started = true;
review.misconceptions = ['multiple-divine-persons'];
review.lastUpdatedAt = 200;
saved.set(`jeremiah-learning-state:${content.standardId}:review`, JSON.stringify(review));
data = getLearningDashboard();
assert.equal(data.active.preset, 'review');
assert.equal(data.inProgress, 1, 'Presets must not double-count a standard');
assert.equal(data.reviewNeeded, 1);
review.milestones.complete = true;
review.currentMoveId = content.instructionalMoves.find((m) => m.type === 'complete').id;
saved.set(`jeremiah-learning-state:${content.standardId}:review`, JSON.stringify(review));
data = getLearningDashboard();
assert.equal(data.mastered, 1);
assert.equal(data.inProgress, 0);
assert.equal(data.reviewNeeded, 0);
assert.equal(data.active.percent, 100);
console.log('Learning dashboard: fresh, resume, review, and completion passed');
